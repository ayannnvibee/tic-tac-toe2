// The Privacy Policy and Terms of Use. Pure Dart, so the app shows them
// offline and tool/export_legal.dart turns them into web pages.

/// Who publishes the game and how to reach them, used in both documents.
abstract final class LegalInfo {
  static const String appName = 'Tic Tac Toe Infinity';
  static const String developer = 'Kodrilla';

  /// Kodrilla's legal hub, which lists every app's documents and how to get
  /// in touch.
  static const String hub = 'kodrilla.com/legal';

  /// Where the two documents live online. Google Play needs the privacy
  /// policy URL. Pages for both are generated by tool/export_legal.dart.
  static const String privacyUrl =
      'https://kodrilla.com/legal/tic-tac-toe/privacy-policy';
  static const String termsUrl =
      'https://kodrilla.com/legal/tic-tac-toe/terms-of-use';

  static const String effectiveDate = '22 October 2026';

  /// Bump when either document changes in a way players must accept again;
  /// the consent screen is then shown once more on the next launch.
  static const int version = 1;
}

/// One heading and its paragraphs.
class LegalSection {
  const LegalSection(this.heading, this.paragraphs);

  final String heading;
  final List<String> paragraphs;
}

/// The two documents, bundled in the app so they can be read offline.
enum LegalDocument {
  privacyPolicy('Privacy Policy', LegalInfo.privacyUrl, _privacySections),
  termsOfUse('Terms of Use', LegalInfo.termsUrl, _termsSections);

  const LegalDocument(this.title, this.url, this.sections);

  final String title;

  /// The same document online.
  final String url;

  final List<LegalSection> sections;
}

